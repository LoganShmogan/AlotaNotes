import 'package:sqflite/sqflite.dart';

import '../core/models.dart';
import '../core/scheduling.dart';
import 'db.dart';

/// Quiz questions generated from (or written for) a note, each one an FSRS
/// card. A new question is due straight away.
class QuestionsRepo {
  final Database _db;
  const QuestionsRepo(this._db);

  Future<List<Choice>> _loadChoices(int questionId) async {
    final rows = await _db.query(
      'question_choices',
      where: 'question_id = ?',
      whereArgs: [questionId],
      orderBy: 'sort_order',
    );
    return rows
        .map((row) => Choice(
              id: row['id'] as int,
              questionId: row['question_id'] as int,
              choiceText: row['choice_text'] as String,
              isCorrect: (row['is_correct'] as int) == 1,
              sortOrder: row['sort_order'] as int,
            ))
        .toList();
  }

  Future<Question> _rowToQuestion(Map<String, Object?> row) async {
    final id = row['id'] as int;
    return Question(
      id: id,
      noteId: row['note_id'] as int,
      questionType: row['question_type'] as String,
      prompt: row['prompt'] as String,
      expectedAnswer: row['expected_answer'] as String,
      card: srsCardFromRow(row)!,
      createdAt: isoToDt(row['created_at'] as String),
      active: (row['active'] as int) == 1,
      isManuallyEdited: (row['is_manually_edited'] as int) == 1,
      choices: await _loadChoices(id),
    );
  }

  Future<Question> create(
    int noteId,
    String questionType,
    String prompt,
    String expectedAnswer, {
    DateTime? now,
    List<(String, bool)>? choices,
  }) async {
    final createdAt = now ?? utcNow();
    final id = await _db.insert('questions', {
      'note_id': noteId,
      'question_type': questionType,
      'prompt': prompt,
      'expected_answer': expectedAnswer,
      ...srsCardToRow(newCard(createdAt)),
      'created_at': dtToIso(createdAt),
      'active': 1,
    });
    if (choices != null) {
      for (var i = 0; i < choices.length; i++) {
        final (text, isCorrect) = choices[i];
        await _db.insert('question_choices', {
          'question_id': id,
          'choice_text': text,
          'is_correct': isCorrect ? 1 : 0,
          'sort_order': i,
        });
      }
    }
    return get(id);
  }

  Future<Question> get(int id) async {
    final rows = await _db.query('questions', where: 'id = ?', whereArgs: [id]);
    if (rows.isEmpty) {
      throw StateError('No question with id $id');
    }
    return _rowToQuestion(rows.first);
  }

  Future<List<Question>> listByNote(int noteId) async {
    final rows = await _db.query('questions', where: 'note_id = ?', whereArgs: [noteId], orderBy: 'id');
    return Future.wait(rows.map(_rowToQuestion));
  }

  /// Every active question, for retention stats.
  Future<List<Question>> listActive() async {
    final rows = await _db.query('questions', where: 'active = 1', orderBy: 'id');
    return Future.wait(rows.map(_rowToQuestion));
  }

  Future<List<Question>> listDue(DateTime now) async {
    final rows = await _db.query(
      'questions',
      where: 'active = 1 AND next_due_at <= ?',
      whereArgs: [dtToIso(now)],
      orderBy: 'next_due_at',
    );
    return Future.wait(rows.map(_rowToQuestion));
  }

  /// Manual edits to an AI-generated question's content (prompt/expected
  /// answer/choices). Always marks `is_manually_edited` so a future
  /// regeneration pass can tell "the user changed this on purpose" apart
  /// from "still exactly what the AI produced" -- same reasoning as the
  /// Python desktop app's plan for this (Docs/flutter_rewrite_plan.md, "a
  /// marker distinct from generated by AI").
  Future<Question> updateContent(
    int id, {
    required String prompt,
    required String expectedAnswer,
    List<(String, bool)>? choices,
  }) async {
    await _db.update(
      'questions',
      {'prompt': prompt, 'expected_answer': expectedAnswer, 'is_manually_edited': 1},
      where: 'id = ?',
      whereArgs: [id],
    );
    if (choices != null) {
      await _db.delete('question_choices', where: 'question_id = ?', whereArgs: [id]);
      for (var i = 0; i < choices.length; i++) {
        final (text, isCorrect) = choices[i];
        await _db.insert('question_choices', {
          'question_id': id,
          'choice_text': text,
          'is_correct': isCorrect ? 1 : 0,
          'sort_order': i,
        });
      }
    }
    return get(id);
  }

  Future<Question> updateScheduling(int id, SrsCard card) async {
    await _db.update('questions', srsCardToRow(card), where: 'id = ?', whereArgs: [id]);
    return get(id);
  }
}
